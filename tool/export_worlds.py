"""
export_worlds.py — the repository's three constructed worlds as world folders (the "P0 round trip" input of the spec):

  reference    = experiment/v16_reference.RefWorld (predicate role = surface lemma, occupancy marker; RESULTS 10b)
  commands     = experiment/v18_commands.CmdWorld (negation as a role around its scope; RESULTS 10d)
  quantifiers  = experiment/v14_quantifiers.QWorld (determiner in det=; quantifier SCOPE NOT EMITTED in v1, per the spec; RESULTS 9c)

Each folder: world.json, legend.json (+ kinds.tsv: the worlds' own categories, rule 20), examples/*.sop generated by the worlds' OWN
generators (same protocol as the scripts: training distribution, held-out formulations, new identities, unseen depth), every top-level
wire with _text, _source=generator and _template; split_hints.json maps the eval files to their splits (the training file's held-out
sentences are drawn by hash inside `sop train`). Nothing in experiment/ is modified; the generators are imported.
Run: python3 tool/export_worlds.py [--out tool/worlds] [--n 2000] [--n_eval 20] [--seed 0] [--worlds reference,commands,quantifiers]
     (the full-size P0 run uses --n 30000 for reference and --n 40000 for commands / quantifiers, as the scripts)
"""
