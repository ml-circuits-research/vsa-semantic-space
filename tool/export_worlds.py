"""
export_worlds.py — the repository's three constructed worlds as world folders (the "P0 round trip" input of the spec):

  reference    = experiment/v16_reference.RefWorld (predicate role = surface lemma, occupancy marker; RESULTS 10b)
  commands     = experiment/v18_commands.CmdWorld (negation as a role around its scope; RESULTS 10d)
  quantifiers  = experiment/v14_quantifiers.QWorld (determiner in det=; quantifier SCOPE NOT EMITTED in v1, per the spec; RESULTS 9c)

Each folder: world.json, legend.json (+ kinds.tsv: the worlds' own categories, rule 20), examples/*.sop generated by the worlds' OWN
generators (same protocol as the scripts: training distribution, held-out formulations, new identities, unseen depth), every top-level
wire with _text, _source=generator and _template; split_hints.json maps the eval files to their splits (the training file's held-out
sentences are drawn by hash inside `sop train`). Nothing in experiment/ is modified; the generators are imported.
Run: python3 tool/export_worlds.py [--out tool/worlds] [--n 2000] [--n_eval 20] [--seed 0] [--worlds reference,commands,quantifiers]
     (the full-size P0 run uses --n 30000 for reference and --n 40000 for commands / quantifiers, as the scripts)
"""
import argparse, datetime, json, os, sys
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")            # generators only: never touch the GPU
HERE = os.path.dirname(os.path.abspath(__file__)); EXP = os.path.join(os.path.dirname(HERE), "experiment")
sys.path.insert(0, EXP); sys.path.insert(0, HERE)
import numpy as np
from sop import soplang
from sop.legend import sha256_file


def write_world(out, name, desc, legend, lexicon, files, hints, language="en"):
    wd = os.path.join(out, name)
    for d in ("examples", "raw", "audit", "model", "runs", "versions", "requests"): os.makedirs(os.path.join(wd, d), exist_ok=True)
    json.dump({"name": name, "language": language, "description": desc, "created": datetime.date.today().isoformat(), "version": legend["version"],
               "models": {"pipeline": "claude-haiku-5-5", "annotate": "claude-haiku-5-5", "second_look": "claude-haiku-5-5", "evolve": "claude-opus-5-5"},
               "second_look_escalate": 0.05, "min_examples": 500, "max_versions_per_run": 3}, open(os.path.join(wd, "world.json"), "w"), indent=1)
    lp = os.path.join(wd, "legend.json"); json.dump(legend, open(lp, "w"), indent=1)
    with open(os.path.join(wd, "kinds.tsv"), "w") as f:
        f.write("# word\tkind\tlemma — the world's own categories (GIVEN, rule 20)\n")
        for w in sorted(lexicon): k, lem = lexicon[w]; f.write(f"{w}\t{k}" + (f"\t{lem}" if lem else "") + "\n")
    sha = sha256_file(lp)
    for fname, rows in files.items():
        doc = soplang.Doc(directives=[("world", name, None), ("legend", sha, None), ("generated", f"export_worlds.py from experiment generators ({datetime.date.today()})", None)])
        n = 0
        for build in rows:
            n = build(doc, n)
        for w in doc.top_level(): w.lines.insert(1, soplang.Line("_world", name))      # the world each top-level wire belongs to (amendment)
        with open(os.path.join(wd, "examples", fname), "w") as f: f.write(soplang.write(doc))
    json.dump(hints, open(os.path.join(wd, "split_hints.json"), "w"), indent=1)
    if not os.path.exists(os.path.join(wd, "status.json")): json.dump({"label": None, "note": "never trained"}, open(os.path.join(wd, "status.json"), "w"))
    print(f"  {name}: {wd} — files " + ", ".join(f"{k} ({len(v)})" for k, v in files.items()) + f"; legend {sha[:19]}…")
    return wd


def sentence_builder(text, template, frame_fn):
    """frame_fn(doc, ids) -> top wire; returns a builder appending the wires to doc"""
    def build(doc, n):
        ids = iter(f"w{n + i}" for i in range(1, 100))
        wires = frame_fn(ids)
        top = wires[0]; top.lines = [soplang.Line("_text", text), soplang.Line("_source", "generator"), soplang.Line("_template", template)] + top.lines
        doc.wires += wires; return n + len(wires)
    return build


def chain(ids, speakers, neg, event_type, roles):
    """says* -> [not] -> event; roles: list of (role, value) with value a str or a callable(ids) -> list of wires (first = filler)"""
    wires = []; prev = None
    def link(w):
        nonlocal prev
        if prev is not None: prev.set("scope", ("ref", w.id))
        prev = w
    for sp in speakers:
        w = soplang.Wire(next(ids), "says"); w.set("speaker", sp); wires.append(w); link(w)
    if neg: w = soplang.Wire(next(ids), "not"); wires.append(w); link(w)
    ev = soplang.Wire(next(ids), event_type); wires.append(ev); link(ev); later = []
    for r, v in roles:
        if v is None: continue
        if callable(v): sub = v(ids); ev.set(r, ("ref", sub[0].id)); later += sub
        else: ev.set(r, v)
    for i in range(len(wires) - 1):              # 'scope' after 'speaker' on says wires, for readability
        pass
    return wires + later


# ---------------------------------------------------------------- reference (v16)
def export_reference(out, n, n_eval, seed):
    import v5_scale as v5, v16_reference as v16
    v5.set_lang("en"); v5.OUTER = [o for o in v5.OUTER if o.index("<P>") > 0]
    w = v16.RefWorld(18, np.random.default_rng(seed)); trP, teP, trO, teO = w.persons[:12], w.persons[12:], w.objects[:12], w.objects[12:]
    held_seen, held_new = v5.split_templates(w); cues_ok, _ = v5.split_templates_rolecues(w)
    roles = [{"id": "agent", "question": "who gives?"}, {"id": "object", "question": "what?"}, {"id": "recipient", "question": "to whom?"}]
    events = {}
    for lem, ev in v16.EVENT.items(): events.setdefault(ev, []).append(lem)
    legend = {"version": 1, "roles": roles, "events": [{"id": e, "verbs": vs} for e, vs in events.items()], "operators": ["says"], "moods": ["statement"],
              "kinds": {"source": "lexicon", "lexicon": "kinds.tsv"}, "values": [],
              "reader": {"predicate_role": True, "occupancy_marker": True, "definite_dets": []}}
    sent_words = {x for ts in w.frames.values() for t in ts for x in t.split() if not x.startswith("{")} | {x for o in v5.OUTER for x in o.split() if not x.startswith("{") and x != "<P>"} \
        | {x for ts in w.omit.values() for t in ts for x in t.split() if not x.startswith("{")} | set(w.persons) | set(w.objects)
    lexicon = {x: (w.cat[x], v16.LEMMA.get(x)) for x in sent_words}
    def row(ev, toks, has_C, template):
        lem = w.surface_verb(toks); speakers = [x for x in ev[4:7] if x is not None]
        return sentence_builder(" ".join(toks), template, lambda ids: chain(ids, speakers, False, v16.EVENT[lem],
                                [("agent", ev[1]), ("object", ev[2]), ("recipient", ev[3] if has_C else None)]))
    trng = np.random.default_rng(200 + seed); train = []
    for _ in range(n):
        d = int(trng.integers(3)); ev = w.event(trP, trO, depth=d)
        if trng.random() < 0.2: t = int(trng.integers(len(v16.OMIT_C))); train.append(row(ev, w.render_omit(ev, t), False, f"omit{t}"))
        else: t = int(trng.choice(v5.TRAIN_T)); train.append(row(ev, w.render(ev, t), True, f"T{t}"))
    def ev_rows(templs, P, O, depth, k):
        rs = []
        for t in templs:
            for _ in range(k): ev = w.event(P, O, depth=depth); rs.append(row(ev, w.render(ev, t), True, f"T{t}"))
        return rs
    files = {"train.sop": train, "eval_new_identities.sop": ev_rows(v5.TRAIN_T, teP, teO, 0, n_eval),
             "eval_role_cues_seen.sop": ev_rows(cues_ok, trP, trO, 0, n_eval), "eval_unseen_transitions.sop": ev_rows(held_new, trP, trO, 0, n_eval),
             "eval_seen_transitions.sop": ev_rows(held_seen, trP, trO, 0, n_eval), "eval_depth3_unseen.sop": ev_rows(v5.TRAIN_T, trP, trO, 3, max(4, n_eval // 2))}
    hints = {"heldout_sentence_share": 0.1, "new_identities": list(teP) + list(teO),
             "file_splits": {"examples/eval_new_identities.sop": "new_identities", "examples/eval_role_cues_seen.sop": "heldout_formulations_role_cues_seen",
                             "examples/eval_unseen_transitions.sop": "heldout_formulations_unseen_transitions",
                             "examples/eval_seen_transitions.sop": "heldout_formulations_seen_transitions", "examples/eval_depth3_unseen.sop": "heldout_depth3"},
             "protocol": f"v16_reference: training formulations T{v5.TRAIN_T} + recipient-less forms (share 0.2) at depths 0-2, persons/objects 0-11; "
                         f"new identities 12-17; held-out formulations: seen transitions {held_seen}, unseen {held_new}, role cues seen {cues_ok}; depth 3 unseen"}
    return write_world(out, "reference", "v16 reference world: transfer events, predicate role, occupancy marker, prefixed reporting", legend, lexicon, files, hints)


# ---------------------------------------------------------------- commands (v18)
def export_commands(out, n, n_eval, seed, name="commands", drop_role=None, raw=False):
    import v18_commands as v18
    w = v18.CmdWorld(np.random.default_rng(seed)); trPat, tePat = v18.PATIENTS[:6], v18.PATIENTS[6:]
    roles = [{"id": "action", "question": "what to do?"}, {"id": "patient", "question": "to what?"}, {"id": "destination", "question": "where to?"}]
    if drop_role: roles = [r for r in roles if r["id"] != drop_role]
    legend = {"version": 1, "roles": roles, "events": [{"id": "command", "verbs": list(v18.ACTIONS)}], "operators": ["not", "says"], "moods": ["command"],
              "kinds": {"source": "lexicon", "lexicon": "kinds.tsv"}, "values": [],
              "reader": {"predicate_role": False, "occupancy_marker": False, "definite_dets": ["the"]}}
    neg_of = {v: k for k, v in v18.ATTRS.items()}
    lexicon = {x: (w.cat[x], neg_of.get(x)) for x in w.vocab}
    def row(ev, toks):
        sc = ev["scope"]
        def patient(ids):
            en = soplang.Wire(next(ids), "entity"); en.set("head", ev["pat"])
            if sc in ("attr", "S+attr"):
                nw = soplang.Wire(next(ids), "not"); nw.set("scope", ev["attr"]); en.set("attr", ("ref", nw.id)); return [en, nw]
            en.set("attr", ev["attr"]); return [en]
        rl = [("action", ev["act"]), ("patient", patient), ("destination", ev["dest"] if ev["form"] == "aff_dest" else None)]
        rl = [(r, v) for r, v in rl if r != drop_role]
        return sentence_builder(" ".join(toks), ev["form"], lambda ids: chain(ids, ev["speakers"], sc in ("S", "S+attr"), "command", rl))
    trng = np.random.default_rng(200 + seed); train, texts = [], []
    for _ in range(n):
        form = list(v18.FORMS)[int(trng.integers(len(v18.FORMS)))]; d = 1 if trng.random() < 0.3 else 0
        ev = w.event(trng, trPat, form, depth=d); toks = w.render(ev, trng); train.append(row(ev, toks)); texts.append(" ".join(toks))
    erng = np.random.default_rng(900 + seed)
    def ev_rows(patients, depth, k):
        rs = []
        for form in v18.FORMS:
            for _ in range(k): ev = w.event(erng, patients, form, depth=depth); toks = w.render(ev, erng); rs.append(row(ev, toks)); texts.append(" ".join(toks))
        return rs
    files = {"train.sop": train, "eval_new_identities.sop": ev_rows(tePat, 0, n_eval), "eval_depth2_unseen.sop": ev_rows(trPat, 2, max(3, n_eval // 2))}
    hints = {"heldout_sentence_share": 0.1, "new_identities": list(tePat),
             "file_splits": {"examples/eval_new_identities.sop": "new_identities", "examples/eval_depth2_unseen.sop": "heldout_depth2"},
             "protocol": "v18_commands: all forms at depth 0 and inside one report (share 0.3), patients 0-5; new patients 6-8; depth 2 unseen"}
    wd = write_world(out, name, "v18 command world: negation as a role around its scope (prohibition vs negated attribute)"
                     + (f"; DELIBERATELY INCOMPLETE legend: role '{drop_role}' removed (evolution test)" if drop_role else ""), legend, lexicon, files, hints)
    if raw:
        with open(os.path.join(wd, "raw", "sentences.txt"), "w") as f: f.write("\n".join(texts) + "\n")
    return wd


# ---------------------------------------------------------------- quantifiers (v14)
def export_quantifiers(out, n, n_eval, seed):
    import v5_scale as v5, v14_quantifiers as v14, v16_reference as v16
    v5.set_lang("en"); v5.OUTER = [o for o in v5.OUTER if o.index("<P>") > 0]
    w = v14.QWorld(np.random.default_rng(seed)); trNP, teNP, trNO, teNO = v14.NOUNS_P[:12], v14.NOUNS_P[12:], v14.NOUNS_O[:12], v14.NOUNS_O[12:]
    roles = [{"id": "agent", "question": "who gives?"}, {"id": "object", "question": "what?"}, {"id": "recipient", "question": "to whom?"}]
    events = {}
    for lem, ev in v16.EVENT.items(): events.setdefault(ev, []).append(lem)
    legend = {"version": 1, "roles": roles, "events": [{"id": e, "verbs": vs} for e, vs in events.items()], "operators": ["says"], "moods": ["statement"],
              "kinds": {"source": "lexicon", "lexicon": "kinds.tsv"}, "values": [],
              "reader": {"predicate_role": False, "occupancy_marker": False, "definite_dets": ["the"]}}
    sent_words = {x for ps in w.qframes.values() for t in ps for x in t.split() if not x.startswith("{")} | set(v14.NOUNS_P) | set(v14.NOUNS_O) \
        | {"every", "each", "some", "a", "certain", "the"} | set(w.persons) | {x for o in v5.OUTER for x in o.split() if not x.startswith("{") and x != "<P>"}
    lexicon = {x: (w.cat[x], v16.LEMMA.get(x)) for x in sent_words}
    def row(ev, toks, t):
        speakers = [x for x in ev[4:7] if x is not None]
        lem = next(v16.LEMMA[x] for x in toks if x in v16.LEMMA)
        def ent(det, noun):
            def f(ids):
                en = soplang.Wire(next(ids), "entity"); en.set("head", noun); en.set("det", det); return [en]
            return f
        return sentence_builder(" ".join(toks), f"Q{t}", lambda ids: chain(ids, speakers, False, v16.EVENT[lem],
                                [("agent", ent(*ev[1])), ("object", ent(*ev[2])), ("recipient", ent(*ev[3]))]))
    trng = np.random.default_rng(200 + seed); train = []
    for _ in range(n):
        if trng.random() < 0.4: ev = w.qevent(trng, depth=int(trng.integers(3)), nouns_p=trNP, nouns_o=trNO, n_quant=0)
        else: ev = w.qevent(trng, depth=int(trng.integers(2)), nouns_p=trNP, nouns_o=trNO)
        t = int(trng.integers(len(v14.PATTERNS))); train.append(row(ev, w.qrender(ev, t, trng), t))
    erng = np.random.default_rng(900 + seed)
    def ev_rows(depth, NP, NO, k, n_quant=None):
        rs = []
        for t in range(len(v14.PATTERNS)):
            for _ in range(k): ev = w.qevent(erng, depth=depth, nouns_p=NP, nouns_o=NO, n_quant=n_quant); rs.append(row(ev, w.qrender(ev, t, erng), t))
        return rs
    files = {"train.sop": train, "eval_new_identities.sop": ev_rows(0, teNP, teNO, n_eval), "eval_depth2_quantified_unseen.sop": ev_rows(2, trNP, trNO, max(3, n_eval // 2)),
             "eval_depth2_affirmative.sop": ev_rows(2, trNP, trNO, max(3, n_eval // 2), n_quant=0)}
    hints = {"heldout_sentence_share": 0.1, "new_identities": list(teNP) + list(teNO),
             "file_splits": {"examples/eval_new_identities.sop": "new_identities", "examples/eval_depth2_quantified_unseen.sop": "heldout_depth2_quantified",
                             "examples/eval_depth2_affirmative.sop": "depth2_affirmative (seen depth, fresh sentences)"},
             "protocol": "v14_quantifiers (E1b protocol): affirmative (all 'the') at depths 0-2 (share 0.4) + unambiguous quantified at depths 0-1; "
                         "nouns 0-11, new nouns 12-17; quantified depth 2 unseen. SCOPE NOT EMITTED (spec v1): det= only; ambiguous sentences not exported"}
    return write_world(out, "quantifiers", "v14 quantifier world: determiners as roles inside the argument (scope not emitted in v1)", legend, lexicon, files, hints)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="sop export")
    ap.add_argument("--out", default=os.path.join(HERE, "worlds")); ap.add_argument("--n", type=int, default=2000); ap.add_argument("--n_eval", type=int, default=20)
    ap.add_argument("--seed", type=int, default=0); ap.add_argument("--worlds", default="reference,commands,quantifiers")
    a = ap.parse_args(argv); os.makedirs(a.out, exist_ok=True)
    print(f"export_worlds: n={a.n} training-distribution sentences per world, n_eval={a.n_eval} per eval template/form, seed {a.seed}")
    for name in a.worlds.split(","):
        {"reference": export_reference, "commands": export_commands, "quantifiers": export_quantifiers}[name](a.out, a.n, a.n_eval, a.seed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
